"""Report rendering to Markdown and PDF. Both use the same validated citations as the report view."""

from __future__ import annotations

import io
import os
from typing import Any

FONT_CANDIDATES = (
    "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
    "/usr/share/fonts/dejavu/DejaVuSans.ttf",
    r"C:\Windows\Fonts\sylfaen.ttf",  # Windows font with Georgian coverage
    r"C:\Windows\Fonts\arial.ttf",
    "/Library/Fonts/Arial Unicode.ttf",
)


def _ref_line(e: dict[str, Any]) -> str:
    loc = e.get("citation_label") or " › ".join(e.get("section_path") or [])
    return f"{e['source_title']}{', ' + loc if loc else ''}"


def render_markdown(r: dict[str, Any]) -> str:
    s = r.get("sections") or {}
    out = [f"# {r['title']}", ""]
    if r["status"] != "complete":
        out += [
            f"> **Incomplete report.** Research stopped before completion ({(r.get('incomplete_reason') or 'unknown').replace('_', ' ')}). Findings below may be partial.",
            "",
        ]
    out += [f"**Research question:** {r['question']}", ""]
    if s.get("executive_summary"):
        out += ["## Executive summary", "", s["executive_summary"], ""]
    if r.get("research_questions"):
        out += ["## Research questions", ""] + [f"{i}. {q}" for i, q in enumerate(r["research_questions"], 1)] + [""]
    findings = s.get("findings") or []
    if findings:
        out += ["## Main findings", ""]
        for f in findings:
            tag = "" if f["kind"] == "supported" else " *(hypothesis — not directly supported by the sources)*"
            out += [f"### {f['heading']}{tag}", "", f["body"], ""]
    cited = [e for e in r.get("evidence", []) if e.get("cited")]
    if cited:
        out += ["## Supporting evidence", ""]
        for e in cited:
            out += [f"- **[{e['label']}]** {_ref_line(e)} — “{e['snippet'][:220].strip()}…”"]
        out.append("")
    contra = s.get("contradictions") or [
        c["description"] + (f" [{', '.join(c['evidence'])}]" if c.get("evidence") else "") for c in r.get("conflicts", [])
    ]
    if contra:
        out += ["## Contradictory evidence", ""] + [f"- {c}" for c in contra] + [""]
    for key, title in (
        ("cross_source_connections", "Cross-book connections"),
        ("limitations", "Limitations"),
        ("open_questions", "Open questions"),
    ):
        if s.get(key):
            out += [f"## {title}", ""] + [f"- {x}" for x in s[key]] + [""]
    if not findings and r.get("evidence"):
        out += ["## Evidence gathered", "", "No AI synthesis was produced. These passages were retrieved for the research questions:", ""]
        out += [f"- **[{e['label']}]** {_ref_line(e)} — “{e['snippet'][:220].strip()}…”" for e in r["evidence"][:40]] + [""]
    if r.get("evidence"):
        out += ["## References", ""] + [f"[{e['label']}]: {_ref_line(e)}" for e in r["evidence"] if e.get("cited") or not findings] + [""]
    out += [
        "---",
        "*Generated by Knowledge Studio from your library. Statements marked as hypotheses are interpretations, not source claims.*",
    ]
    return "\n".join(out)


def _font() -> tuple[str, bool]:
    from reportlab.pdfbase import pdfmetrics
    from reportlab.pdfbase.ttfonts import TTFont

    from app.core.config import get_settings

    for path in (get_settings().pdf_font_path, os.environ.get("PDF_FONT_PATH", ""), *FONT_CANDIDATES):
        if path and os.path.exists(path):
            try:
                pdfmetrics.registerFont(TTFont("KSUnicode", path))
                return "KSUnicode", True
            except Exception:  # noqa: BLE001,S112
                continue
    return "Helvetica", False


class ExportTooLong(Exception):
    def __init__(self, pages: int) -> None:
        super().__init__(f"{pages} pages")
        self.pages = pages


def render_pdf(r: dict[str, Any], *, max_pages: int) -> bytes:
    from xml.sax.saxutils import escape

    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer

    font, unicode_ok = _font()
    ss = getSampleStyleSheet()
    body = ParagraphStyle("b", parent=ss["BodyText"], fontName=font, fontSize=10.5, leading=15)
    h1 = ParagraphStyle("h1", parent=ss["Heading1"], fontName=font, fontSize=18, leading=22)
    h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName=font, fontSize=13.5, leading=18, spaceBefore=10)
    h3 = ParagraphStyle("h3", parent=ss["Heading3"], fontName=font, fontSize=11.5, leading=15)
    note = ParagraphStyle("n", parent=body, textColor="#8a5a00", backColor="#fff6e0", borderPadding=6)
    small = ParagraphStyle("s", parent=body, fontSize=8.5, leading=11, textColor="#555555")
    story: list[Any] = []
    for line in render_markdown(r).splitlines():
        t = line.rstrip()
        if not t:
            story.append(Spacer(1, 4))
            continue
        txt = escape(t.lstrip("#> -").strip()).replace("**", "")
        if t.startswith("# "):
            story.append(Paragraph(txt, h1))
        elif t.startswith("## "):
            story.append(Paragraph(txt, h2))
        elif t.startswith("### "):
            story.append(Paragraph(txt, h3))
        elif t.startswith(">"):
            story.append(Paragraph(txt, note))
        elif t.startswith("- ") or t.startswith("["):
            story.append(Paragraph("• " + txt if t.startswith("- ") else txt, small if t.startswith("[") else body))
        elif t == "---":
            story.append(Spacer(1, 10))
        else:
            story.append(Paragraph(txt.replace("*", ""), body))
    if not unicode_ok:
        story.append(
            Paragraph("Note: no Unicode font was found on the server (set PDF_FONT_PATH); some non-Latin characters may not render.", small)
        )
    buf = io.BytesIO()
    pages = {"n": 0}

    def on_page(canvas: Any, doc: Any) -> None:
        pages["n"] = doc.page
        canvas.setFont(font, 8)
        canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"{r['title'][:80]} · page {doc.page}")

    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm, topMargin=2 * cm, bottomMargin=2 * cm, title=r["title"]
    )
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    if pages["n"] > max_pages:
        raise ExportTooLong(pages["n"])
    return buf.getvalue()
